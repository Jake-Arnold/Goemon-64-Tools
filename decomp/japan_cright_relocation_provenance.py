EXPECTED_LOST = Counter({(SECTION, addr, kind, VALUE, SYMBOL):1 for addr,kind in (
    (0x80212550,'R_MIPS_HI16'),(0x80212590,'R_MIPS_LO16'))})


def _check_splat_provenance(auto_symbols: str, explicit_symbols: list[str]):
    """Check the precise Splat provenance; never guess from a D_* name."""
    matches = re.findall(r'(?m)^\s*D_3B07A\s*=\s*(0x[0-9A-Fa-f]+)\s*;',auto_symbols)
    if len(matches)!=1 or int(matches[0],16)!=VALUE:
        raise ValueError('BLOCKED_PROVENANCE: generated D_3B07A definition absent/drifted')
    if not explicit_symbols:
        raise ValueError('BLOCKED_PROVENANCE: explicit symbol maps unavailable')
    if any(re.search(r'(?<![A-Za-z_0-9])D_3B07A(?![A-Za-z_0-9])',s) for s in explicit_symbols):
        raise ValueError('BLOCKED_PROVENANCE: D_3B07A is explicitly authored, not solely autogenerated')


def reconcile_research(original_rel: Counter, candidate_rel: Counter, *,
                       original_rom: bytes, candidate_rom: bytes,
                       auto_symbols: str, explicit_symbols: list[str],
                       original_reloc_sha256: str, candidate_reloc_sha256: str):
    """Audit exactly one known offset-alias delta, retaining all other tuples.

    No wildcard and no reconstructed/added relocation. This result is not G2.
    """
    if not isinstance(original_rel,Counter) or not isinstance(candidate_rel,Counter):
        raise TypeError('Relocations must be full Counter multisets')
    if len(original_rom)!=33554432 or hashlib.sha1(original_rom).hexdigest()!=ORIGINAL_SHA1:
        raise ValueError('FAILED_ROM: unauthenticated original Japan ROM')
    if candidate_rom!=original_rom:
        raise ValueError('FAILED_ROM: candidate differs from the original 32 MiB image')
    code=original_rom[ORIGINAL_ROM_OFFSET:ORIGINAL_ROM_OFFSET+FUNCTION_SIZE]
    if hashlib.sha256(code).hexdigest()!=ORIGINAL_CODE_SHA256:
        raise ValueError('FAILED_CODE: initializer code SHA-256 differs')
    for site,word in SITE_WORDS.items():
        off=ORIGINAL_ROM_OFFSET+(site-ORIGINAL_VMA)
        if int.from_bytes(original_rom[off:off+4],'big')!=word:
            raise ValueError(f'FAILED_CODE: offset arithmetic instruction changed at {site:#x}')
    _check_splat_provenance(auto_symbols,explicit_symbols)
    if sum(original_rel.values())!=80747 or sum(candidate_rel.values())!=80745:
        raise ValueError('FAILED_RELOC: canonical full-ELF relocation counts changed')
    if (original_reloc_sha256!=BASELINE_RELOC_SHA256 or
            candidate_reloc_sha256!=CANDIDATE_RELOC_SHA256):
        raise ValueError('FAILED_RELOC: full-ELF canonical relocation fingerprint drift')
    removed=original_rel-candidate_rel
    added=candidate_rel-original_rel
    if removed!=EXPECTED_LOST or added:
        raise ValueError(f'FAILED_RELOC: unexpected loss/addition {list(removed.items())[:6]} / {list(added.items())[:6]}')
    for row,multiplicity in EXPECTED_LOST.items():
        if original_rel[row]!=1 or candidate_rel[row]!=0 or multiplicity!=1:
            raise ValueError('FAILED_RELOC: expected loss not unique')
    return {
        'format':'goemon-japan-cright-splat-offset-provenance-audit-v1',
        'status':'RESEARCH_PROVENANCE_RECONCILED_NOT_G2',
        'region':'japan_0','name':'func_80212514_5CDAA4',
        'original_sha1':ORIGINAL_SHA1,
        'original_function_bytes_exact':FUNCTION_SIZE,
        'original_relocation_count':80747,'candidate_relocation_count':80745,
        'all_other_relocation_records_preserved':True,
        'synthetic_annotations_absent':[
            {'section':s,'vma':f'{pc:#x}','type':kind,'value':f'{v:#x}','symbol':sym}
            for s,pc,kind,v,sym in sorted(EXPECTED_LOST)
        ],
        'source_note':'D_3B07A was generated by Splat, not found in authored symbol map; linked MIPS offset arithmetic and ROM bytes exact',
        'promotion_status':'BLOCKED_RELOCATION_POLICY_REVIEW'
    }


def audit_workspace(checkout: Path, baseline: Path):
    """Use unmodified project all-relocation extraction; no normalization."""
    from .glitch_g2_promotion import all_semantic_relocations
    from . import japan_cright_promotion as cr
    from . import overlay_crossregion47 as cross
    co=checkout.resolve();baseline=baseline.resolve()
    original=(co/'config/japan_0/baserom.decompressed.z64').read_bytes()
    candidate_rom=(co/'build/japan_0/mnsg.z64').read_bytes()
    base_rom=(baseline/'build/japan_0/mnsg.z64').read_bytes()
    if base_rom!=original:raise ValueError('FAILED_ROM: prior accepted baseline not exact')
    oldelf=baseline/'build/japan_0/mnsg.elf'
    newelf=co/'build/japan_0/mnsg.elf'
    ids0=cross._funcs(oldelf);ids1=cross._funcs(newelf)
    if ids0!=ids1 or sum(ids0.values())!=7376:raise ValueError('FAILED_ELF: function identities changed')
    orig,n0,h0=all_semantic_relocations(oldelf)
    cand,n1,h1=all_semantic_relocations(newelf)
    explicit_folder=co/'config/japan_0/symbol_addrs'
    explicit=[p.read_text(errors='replace') for p in sorted(explicit_folder.rglob('*')) if p.is_file()]
    result=reconcile_research(orig,cand,original_rom=original,candidate_rom=candidate_rom,
            auto_symbols=(co/'.splat/japan_0/undefined_syms_auto.ld').read_text(),
            explicit_symbols=explicit,original_reloc_sha256=h0,candidate_reloc_sha256=h1)
    prior=cr.c_identities(oldelf);after=cr.c_identities(newelf)
    if len(prior)!=2369 or len(after)!=2370 or after-prior!={cr.TARGET} or prior-after:
        raise ValueError('FAILED_INVENTORY: only C-Right may change ASM/C ownership')
    # Link to stage & source evidence, preserving hash guards.
    stage=json.loads((co/cr.STAGE).read_text())
    if stage.get('source_sha256')!=cr.SRC_SHA or stage.get('name')!=cr.TARGET:
        raise ValueError('FAILED_SOURCE: stage SHA or target changed')
    if cr.sha((co/cr.C_PATH).read_bytes())!=cr.SRC_SHA:
        raise ValueError('FAILED_SOURCE: compiled C source drift')
    result.update(elf_positive_function_identities=7376,accepted_source_count_before=2369,
                  candidate_source_count=2370,candidate_original_bytes=127008,
                  provenance_policy_reviewed=False,
                  original_relocations_sha256=h0,candidate_relocations_sha256=h1)
    return result
