"""Original-address, fail-closed 15-unit / 15-C native-exact micro stage after accepted 1463-C USA production.

Builds native IDO objects from the Git-fingerprinted research sources, slices
only still-ASM-owned ranges, and requires exact whole-ROM/ELF/relocation proof.
"""
from __future__ import annotations
from collections import Counter,defaultdict
import hashlib,json,re,subprocess
from pathlib import Path
from . import overlay_wide132 as wide
from . import overlay_crossregion47 as cross

ROOT=Path(__file__).resolve().parent
SOURCE_BASE=ROOT/'research/pending_micro15_20261119/sources'
FIXTURE=ROOT/'research/pending_micro15_20261119/promotion_manifest.json'
STAGE_FORMAT='goemon-usa-micro15-after-1463-v1'
SHA1='6ea0ed71032ce08fc2745f412d84936382197494'
SECTIONS={'file_19', 'file_14', 'file_79', 'file_13', 'file_15', 'file_12', 'file_47'}

def sha256(b):return hashlib.sha256(b).hexdigest()
def functions(fixture):return [f for u in fixture['units'] for f in u['functions']]
def load_fixture():
    j=json.loads(FIXTURE.read_text())
    if j['format']!=STAGE_FORMAT or j['original_rom_sha1']!=SHA1 or j['original_canonical_count']!=1463:raise ValueError('Unreviewed micro15 fixture')
    if len(j['units'])!=15 or len(functions(j))!=15 or sum(x['size'] for x in functions(j))!=296:raise ValueError('Micro15 changed count/bytes')
    names,offsets,units=set(),set(),set()
    for u in j['units']:
        if u['section'] not in SECTIONS or not re.fullmatch(r'micro15_[0-9]{3}',u['name']) or u['name'] in units:raise ValueError('Unexpected micro15 unit')
        units.add(u['name']);cur=u['rom_offset']
        for f in u['functions']:
            if (f['rom_offset']!=cur or f['name'] in names or f['rom_offset'] in offsets or
                not re.fullmatch(r'func_([0-9A-F]{8})_([0-9A-Fa-f]+)',f['name'])):raise ValueError('Micro15 function ownership mismatch '+f['name'])
            m=re.fullmatch(r'func_([0-9A-F]{8})_([0-9A-Fa-f]+)',f['name'])
            if int(m[1],16)!=f['vma'] or int(m[2],16)!=f['rom_offset'] or f['size']%4 or f['size']<8:raise ValueError('Micro15 VMA/size mismatch')
            names.add(f['name']);offsets.add(f['rom_offset']);cur+=f['size']
        if cur-u['rom_offset']!=u['size']:raise ValueError('Micro15 non-contiguous source '+u['name'])
    return j

def validate_sources(rom,fixture,source_root=SOURCE_BASE):
    if len(rom)!=33554432 or hashlib.sha1(rom).hexdigest()!=SHA1:raise ValueError('Invalid USA original ROM')
    for u in fixture['units']:
        raw=(source_root/(u['name']+'.c')).read_bytes()
        if sha256(raw)!=u['source_sha256']:raise ValueError('Micro15 native source hash mismatch: '+u['name'])
        for f in u['functions']:
            off,size=f['rom_offset'],f['size']
            if sha256(rom[off:off+size])!=f['original_code_sha256']:raise ValueError('Micro15 original anchor mismatch: '+f['name'])

def find_owners(checkout,fixture):
    return wide.find_owners(checkout,{'functions':functions(fixture)})

def parent_targets(owners):return wide.parent_targets(owners)

def stage_linker(checkout,rom,fixture,owners,source_root=SOURCE_BASE):
    validate_sources(rom,fixture,source_root)
    checkout=Path(checkout);ld=checkout/'.splat/usa/mnsg.ld';text=ld.read_text()
    by_parent=defaultdict(list)
    for u in fixture['units']:
        parents=set()
        for f in u['functions']:
            p,sz=owners[f['name']]
            if sz!=f['size']:raise ValueError('Original ASM extent changed '+f['name'])
            parents.add(p)
        if len(parents)!=1:raise ValueError('Micro15 source unit spans multiple active ASM objects '+u['name'])
        by_parent[parents.pop()].append(u)
    assembly=[];parents=[]
    for parent,entries in sorted(by_parent.items()):
        entries.sort(key=lambda u:u['rom_offset'])
        full=(checkout/'asm/usa'/(parent+'.s')).read_text()
        spl=full.find('/* Generated by')
        if spl<0:
            first=wide.FUNCTION_MARKER.search(full);word=wide.TEXT_WORD.search(full)
            if first is None or word is None:raise ValueError('Unrecognised ASM provenance '+parent)
            spl=min(first.start(),word.start())
        header,body=full[:spl],full[spl:];begin,end=wide._span(body)
        cross._object_nontext_empty(checkout/f'build/usa/asm/usa/{parent}.s.o')
        replacements=[];cursor=0;position=begin
        for i,u in enumerate(entries):
            fs=u['functions'];first,last=fs[0]['name'],fs[-1]['name'];off=u['rom_offset'];end_c=off+u['size']
            m=re.search(r'(?m)^nonmatching '+re.escape(first)+r', 0x([0-9A-Fa-f]+)$',body)
            if m is None or int(m[1],16)!=fs[0]['size'] or off<position or end_c>end or m.start()<cursor:raise ValueError('Micro15 lost ASM start '+first)
            leading=body[cursor:m.start()]
            if position<off:
                if wide._span(leading)!=(position,off):raise ValueError('Micro15 lost intervening original ASM')
                asm=f'{parent}_wm15_{i:02}';(checkout/'asm/usa'/(asm+'.s')).write_text(header+leading)
                obj=f'build/usa/asm/usa/{asm}.s.o';replacements.append(obj);assembly.append({'object':obj,'start':position,'end':off})
            elif wide.TEXT_WORD.search(leading):raise ValueError('Unexpected ASM before micro15 C')
            stop=body.find('endlabel '+last,m.end())
            if stop<0:raise ValueError('Missing last original endlabel '+last)
            stop+=len('endlabel '+last);block=body[m.start():stop]
            if wide._span(block)!=(off,end_c) or len(wide.FUNCTION_MARKER.findall(block))!=len(fs):raise ValueError('Micro15 contiguous C unit extent differs '+u['name'])
            got=[(n,int(s,16)) for n,s in wide.FUNCTION_MARKER.findall(block)]
            if got != [(f['name'],f['size']) for f in fs]:raise ValueError('Micro15 C unit symbol order/extent differs')
            output=checkout/'src'/(u['name']+'.c')
            if output.exists():raise ValueError('Micro15 C file collision '+u['name'])
            output.write_bytes((source_root/(u['name']+'.c')).read_bytes())
            replacements.append(f'build/usa/src/{u["name"]}.c.o')
            cursor=stop;position=end_c
        if position<end:
            tail=body[cursor:]
            if wide._span(tail)!=(position,end):raise ValueError('Micro15 trailing ASM changed '+parent)
            asm=f'{parent}_wm15_{len(entries):02}';(checkout/'asm/usa'/(asm+'.s')).write_text(header+tail)
            obj=f'build/usa/asm/usa/{asm}.s.o';replacements.append(obj);assembly.append({'object':obj,'start':position,'end':end})
        old=f'build/usa/asm/usa/{parent}.s.o(.text);'
        if text.count(old)!=1:raise ValueError('Micro15 ASM ownership not unique '+parent)
        text=text.replace(old,'\n'.join(p+'(.text);' for p in replacements),1)
        for section in ('.data','.rodata','.bss'):
            old=f'build/usa/asm/usa/{parent}.s.o({section});'
            if text.count(old)>1:raise ValueError('Micro15 extra nontext owner '+parent)
            text=text.replace(old,'')
        children=[(a['object'],a['start'],a['end']) for a in assembly if a['object'].startswith(f'build/usa/asm/usa/{parent}_wm15_')]
        children += [(f'build/usa/src/{u["name"]}.c.o',u['rom_offset'],u['rom_offset']+u['size']) for u in entries]
        children.sort(key=lambda x:x[1])
        if children[0][1]!=begin or children[-1][2]!=end or any(a[2]!=b[1] for a,b in zip(children,children[1:])):raise ValueError('Micro15 partition changed original ASM')
        parents.append({'name':parent,'start':begin,'end':end,'children':children})
    oldtext=ld.read_text();found=set();region=None
    for line in oldtext.splitlines():
        section=re.match(r'^\s*\.(main|file_\d+)\s+0x[0-9A-Fa-f]+\s*:\s*AT\(',line)
        if section:region=section.group(1)
        for parent in by_parent:
            if f'build/usa/asm/usa/{parent}.s.o(.text);' in line:
                if region not in SECTIONS:raise ValueError('Micro15 original linked overlay differs '+str(region))
                found.add(parent)
    if found!=set(by_parent):raise ValueError('Micro15 output section ownership missing')
    for section in {u['section'] for u in fixture['units']}:
        pattern=r'(?m)^(\s*\.'+re.escape(section)+r'\s+0x[0-9A-Fa-f]+\s*:\s*AT\([^)]+\)) SUBALIGN\(16\)'
        text,n=re.subn(pattern,r'\1 SUBALIGN(4)',text)
        if n>1:raise ValueError('Ambiguous micro15 section subalignment '+section)
    ld.write_text(text)
    return {'units':fixture['units'],'functions':functions(fixture),'assembly':assembly,'parents':parents,'linker_sha256':sha256(text.encode())}

def object_targets(plan):return [f'build/usa/src/{u["name"]}.c.o' for u in plan['units']]+[a['object'] for a in plan['assembly']]

def pack_objects(checkout,rom,plan):
    checkout=Path(checkout);c=[];asm=[]
    for u in plan['units']:
        path=checkout/f'build/usa/src/{u["name"]}.c.o'
        symbols=subprocess.check_output(['readelf','-Ws',str(path)],text=True)
        got={}
        for line in symbols.splitlines():
            parts=line.split()
            if len(parts)>=8 and parts[3]=='FUNC' and parts[6] not in ('UND','ABS') and parts[7].startswith('func_'):
                got[parts[7]]=(int(parts[1],16),int(parts[2]))
        expected={f['name']:(f['rom_offset']-u['rom_offset'],f['size']) for f in u['functions']}
        if got!=expected:raise ValueError('Micro15 C unit changed original function offsets/sizes: '+u['name']+' '+str(got))
        unresolved='R_MIPS_' in subprocess.check_output(['readelf','-Wr',str(path)],text=True)
        c.append({'source':u['name'],'has_prelink_relocations':unresolved,**cross._trim_object(path,u['size'],rom[u['rom_offset']:u['rom_offset']+u['size']],name=None if unresolved else None)})
    for a in plan['assembly']:
        asm.append({'object':a['object'],**cross._trim_object(checkout/a['object'],a['end']-a['start'],rom[a['start']:a['end']])})
    return {'functions':len(plan['functions']),'units':len(c),'instruction_bytes':sum(x['size'] for x in plan['functions']),'c':c,'asm':asm}

def verify_link(baseline,accepted_elf,candidate,rom,plan,fixture):
    baseline=Path(baseline);candidate=Path(candidate);accepted_elf=Path(accepted_elf)
    image=(candidate/'build/usa/mnsg.z64').read_bytes()
    if len(image)!=33554432 or image!=rom or hashlib.sha1(image).hexdigest()!=SHA1:raise ValueError('Micro15 whole-ROM 32MiB mismatch')
    old=baseline/'build/usa/mnsg.elf';new=candidate/'build/usa/mnsg.elf'
    oldsyms=cross._funcs(old);prevsyms=cross._funcs(accepted_elf);newsyms=cross._funcs(new)
    if sum(oldsyms.values())!=7376 or prevsyms!=newsyms:raise ValueError('Micro15 changed accepted ELF positive FUNC identity')
    from .overlay_wide132 import _main_entry_relocations
    before=_main_entry_relocations(accepted_elf);after=_main_entry_relocations(new)
    # REL record ordering can change when adjacent ASM becomes C. Compare the
    # complete site/type/symbol/addend multiset, not the display order of readelf.
    if set(before)!=set(after) or any(Counter(before[section])!=Counter(after[section]) for section in before):
        raise ValueError('Micro15 main/entry semantic relocations changed')
    all_before=cross._relocations(accepted_elf);all_after=cross._relocations(new)
    if set(all_before)!=set(all_after) or any(Counter(all_before[s])!=Counter(all_after[s]) for s in all_before):raise ValueError('Micro15 accepted-baseline overlay semantic relocations changed')
    maptext=(candidate/'build/usa/mnsg.map').read_text();funcs=set(newsyms.elements())
    for u in fixture['units']:
        obj=f'build/usa/src/{u["name"]}.c.o'
        if obj not in maptext:raise ValueError('Micro15 native C unit absent from ELF map: '+u['name'])
        for f in u['functions']:
            if ((f['name'],f['vma'],f['size']) not in funcs or f['name']+'.NON_MATCHING' in maptext or
                rom[f['rom_offset']:f['rom_offset']+f['size']]!=image[f['rom_offset']:f['rom_offset']+f['size']]):raise ValueError('Micro15 original linked function identity mismatch: '+f['name'])
    return {'status':'PASS','count':15,'original_instruction_bytes':296,'original_ROM_SHA1':SHA1,'matched_ROM_bytes':len(image),'identical_accepted_ELF_FUNC_identities':7376,'identical_accepted_semantic_relocations':{s:len(v) for s,v in all_after.items()},'C_translation_units':len(fixture['units']),'retained_ASM_fragments':len(plan['assembly'])}
