#!/usr/bin/env python3
"""Research-only exact original-USA linker scratch. Never edits production checkout."""
from pathlib import Path
import os
import hashlib, json, re, shutil, subprocess, struct

REF=Path(os.environ['GOEMON_BASELINE']).resolve()
OUT=Path(os.environ['GOEMON_CANDIDATE']).resolve()
ARCH=Path(os.environ['GOEMON_C_SOURCE_ARCHIVE']).resolve()
ROM=REF/'config/usa/baserom.decompressed.z64'
SEGMENTS={'file_12':'5C8770','file_13':'5F6840','file_14':'63A2B0','file_15':'65E310',
          'file_17':'66C250','file_18':'676C80','file_19':'694CA0'}

manifest=json.loads((ARCH/'manifest.json').read_text())
entries=[f for f in manifest['candidates'] if not f.get('already_promoted_usa') and f['segment'] in SEGMENTS]
assert len(entries)==47, len(entries)
assert sum(f['size'] for f in entries)==2220
assert hashlib.sha1(ROM.read_bytes()).hexdigest()=='6ea0ed71032ce08fc2745f412d84936382197494'
assert len({f['name'] for f in entries})==47
assert not OUT.exists(), 'Fail-closed: this scratch path already exists'
shutil.copytree(REF,OUT)
ld=OUT/'.splat/usa/mnsg.ld'
script=ld.read_text()
report=[]
for section,orig in SEGMENTS.items():
    group=sorted([f for f in entries if f['segment']==section],key=lambda f:int(f['usa_rom_offset'],16))
    if not group:continue
    asm=OUT/f'asm/usa/{orig}.s'
    body=asm.read_text()
    header=body[:body.index('/* Generated by')]
    source_line=f'        build/usa/asm/usa/{orig}.s.o(.text);'
    assert script.count(source_line)==1
    chunks=[]
    current=0
    for n,f in enumerate(group):
        name=f['name'];rom=int(f['usa_rom_offset'],16);size=f['size']
        src=ARCH/'src'/f'{name}.c'
        assert hashlib.sha256(src.read_bytes()).hexdigest()==f['source_sha256'],name+' SHA mismatch'
        code=ROM.read_bytes()[rom:rom+size]
        assert len(code)==size
        expression=r'(?m)^nonmatching '+re.escape(name)+r', 0x([0-9a-fA-F]+)$'
        matcher=re.search(expression,body)
        assert matcher,name+' absent from source ASM'
        assert int(matcher.group(1),16)==size,name+' size mismatch'
        left=matcher.start()
        assert left>=current
        previous=body[current:left]
        if previous.strip() and previous.strip()!=header.strip():
            path=f'asm/usa/{orig}_scratch_part_{n:03}.s'
            (OUT/path).write_text(header+previous if current else previous)
            chunks.append(('asm',path))
        # Do not cut anywhere inside an original nonmatching FUNC block.
        end_marker='endlabel '+name
        e=body.index(end_marker,matcher.end())+len(end_marker)
        assert '\nnonmatching' not in body[matcher.start():e], 'Unexpected interposed function'
        current=e
        dest=OUT/f'src/promotion_scratch/{name}.c'
        dest.parent.mkdir(parents=True,exist_ok=True)
        shutil.copyfile(src,dest)
        chunks.append(('c',f'src/promotion_scratch/{name}.c'))
        report.append({'name':name,'section':section,'rom_offset':f['usa_rom_offset'],'size':size,
                       'source_sha256':f['source_sha256']})
    end=body[current:]
    if end.strip():
        path=f'asm/usa/{orig}_scratch_part_{len(group):03}.s'
        (OUT/path).write_text(header+end)
        chunks.append(('asm',path))
    assert chunks and chunks[0][0]=='asm',f'No prefix ASM for {section}'
    asm.rename(asm.with_suffix('.orig-scratch'))
    first=chunks[0][1]
    assert first.endswith('.s')
    replacement='\n'.join(f'        build/usa/{path}.o(.text);' for _,path in chunks)
    script=script.replace(source_line,replacement)
    script=script.replace(f'build/usa/asm/usa/{orig}.s.o(',f'build/usa/{first}.o(')
    # Override subsegment alignment to 4 (original MIPS word alignment).  Original
    # overlay text ends on 16-byte boundary, so complete ROM layout is invariant.
    line=f'.file_{section.removeprefix("file_")} '
    matches=re.findall(r'(?m)^    '+re.escape(line)+r'0x[0-9A-F]+ : AT\([^)]+\) SUBALIGN\(16\)',script)
    assert len(matches)==1,(section,matches)
    script=script.replace(matches[0],matches[0].replace('SUBALIGN(16)','SUBALIGN(4)'))
    print(section,'functions',len(group),'ASM parts',sum(t=='asm' for t,_ in chunks),
          'C parts',sum(t=='c' for t,_ in chunks),flush=True)
ld.write_text(script)
(OUT/'promotion_scratch_metadata.json').write_text(json.dumps({'status':'RESEARCH_ONLY_NOT_PRODUCTION','functions':report},indent=2))
print('STAGED',len(report),'FUNCTIONS',sum(x['size'] for x in report),'BYTES',flush=True)
