#!/usr/bin/env python3
"""Replay isolated native matches, using a private pristine USA upstream tree.
No game bytes, objects, generated ASM or compiler files are written into Git.
Usage: python3 replay.py /path/to/pristine/mnsg /empty/private/work
Run with pinned MIPS binutils on PATH and their runtime library path set.
"""
import argparse, hashlib, json, pathlib, re, subprocess, sys
D=pathlib.Path(__file__).resolve().parent
ROOT=D.parents[2]; sys.path.insert(0,str(ROOT))
from decomp import native_probe_helpers251 as probe, verify
from decomp.consolidated_batch_promotion import exact, rels, glitch, text
P=pathlib.Path
sha=lambda b:hashlib.sha256(b).hexdigest()
def run(args,co):
    return subprocess.check_output([str(x) for x in args],cwd=co,stderr=subprocess.STDOUT,text=True)
def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('upstream',type=P);ap.add_argument('work',type=P);a=ap.parse_args();co=a.upstream.resolve();w=a.work.resolve();w.mkdir(parents=True,exist_ok=False)
    rom=(co/'config/usa/baserom.decompressed.z64').read_bytes(); assert len(rom)==33554432 and hashlib.sha1(rom).hexdigest()=='6ea0ed71032ce08fc2745f412d84936382197494'
    assert (co/'build/usa/mnsg.z64').read_bytes()==rom
    cc=co/'tools/ido-5.3/cc';assert sha(cc.read_bytes())=='76d796c9591c9f5504949f85b29c32a6039a663791afe2f36f34ca18425b64d0'
    claims=verify.claimed_functions(verify.load_manifest(ROOT/'decomp/manifest.json')); spans=[(x['rom_offset'],x['rom_offset']+x['size']) for x in claims]
    elf_symbols=run(['readelf','-Ws',co/'build/usa/mnsg.elf'],co)
    syms={}
    for l in elf_symbols.splitlines():
        p=l.split()
        if len(p)>=8 and p[0].endswith(':') and p[4]=='GLOBAL': syms.setdefault(p[7],set()).add(int(p[1],16))
    ledger=ROOT/'decomp/COMPILER_QUIRKS.md';out=[]
    for f in json.loads((D/'candidates.json').read_text()):
        n=f['name'];off=f['rom_offset'];z=f['original_bytes'];vma=f['vma'];raw=rom[off:off+z]; assert not any(lo<off+z and off<hi for lo,hi in spans),n
        q=w/n;q.mkdir();owner=co/'asm/usa'/f['owner'];probe.get_original_splat_lines(owner,n,off,vma,z,raw)
        asm=owner.read_text();block=re.search(r'^nonmatching '+re.escape(n)+r',.*?^endlabel '+re.escape(n)+r'\s*$',asm,re.M|re.S);assert block
        ref=q/'reference.s';ref.write_text(asm[:asm.index('/* Generated by')]+block[0]+'\n');ro=q/'reference.o'
        run(['mips-linux-gnu-as','-EB','-mtune=vr4300','-march=vr4300','-mabi=32','-Iinclude','-I.','-o',ro,ref],co)
        assert len(rels(ro))==f['relocation_count']; definitions=[]
        for sym in sorted({x[2] for x in rels(ro)}):
            assert len(syms[sym])==1,(n,sym);definitions+=['--defsym',f'{sym}=0x{next(iter(syms[sym])):x}']
        ld=q/'link.ld';ld.write_text(f'SECTIONS {{ .text 0x{vma:x} : SUBALIGN(4) {{ *(.text) }} /DISCARD/ : {{ *(.reginfo) *(.MIPS.abiflags) *(.pdr) *(.comment) *(.mdebug*) *(.gptab*) }} }}\n')
        attempts=[]
        def compile_source(key,flags,label):
            source=D/f[key];assert sha(source.read_bytes())==f[key+'_sha256'];
            for h,hs in f['headers_sha256'].items():assert sha((source.parent/h).read_bytes())==hs
            ls=sha(ledger.read_bytes());ob=q/(label+'.o');cmd=[cc,*flags,'-I'+str(source.parent),'-o',ob,source];run(cmd,co)
            result=exact(ob,ro,f)
            rb,cb=text(ro),text(ob);first=next((i for i in range(0,z,4) if rb[i:i+4]!=cb[i:i+4]),None)
            kind=None if result else ('instruction_or_extent' if first is not None else 'ELF_extent_or_relocation')
            outcome='NO_NEW_COMPILER_FINDING'
            if label=='positive' and '-O0' in flags:outcome='NEW_REPRODUCIBLE_QUIRK'
            attempts.append(dict(label=label,flags=flags,source_sha256=f[key+'_sha256'],ledger_sha256=ls,object_exact=result,first_mismatch_offset=first,mismatch_class=kind,compiler_quirk_outcome=outcome))
            return ob,result
        ob,ok=compile_source('source',f['flags'],'positive');assert ok,n;glitch.check_nontext(ob)
        neg,ok=compile_source('negative_source',f['flags'],'negative');assert not ok,n
        if '-O0' in f['flags']:
            _,ok=compile_source('source',['-O2' if x=='-O0' else x for x in f['flags']],'default');assert not ok,n
        for label,obj in [('candidate',ob),('reference',ro)]:
            elf=q/(label+'.elf');b=q/(label+'.bin');run(['mips-linux-gnu-ld','-EB','-m','elf32btsmip','--emit-relocs','-T',ld,*definitions,'-o',elf,obj],co);run(['mips-linux-gnu-objcopy','-O','binary','-j','.text',elf,b],co)
            linked=b.read_bytes();assert linked[:z]==raw and not any(linked[z:]),n
            symbols=run(['readelf','-Ws',elf],co); assert probe.check_size(symbols,n,z)[0],n
            assert any(l.split()[1].lower()==f'{vma:08x}' and l.split()[-1]==n for l in symbols.splitlines() if len(l.split())>=8),n
        assert rels(q/'candidate.elf')==rels(q/'reference.elf'),n
        out.append(dict(name=n,region='usa',rom_offset=off,vma=vma,original_bytes=z,owner=f['owner'],original_code_sha256=sha(raw),source_sha256=f['source_sha256'],negative_sha256=f['negative_source_sha256'],relocations=f['relocation_count'],attempts=attempts,original_address_bytes_exact=True,reference_bytes_exact=True,elf_extent_exact=True,linked_relocations_exact=True,status='ISOLATED_EXACT',full_rom_candidate='NOT_RUN'))
        print(n,z,'ISOLATED_EXACT',flush=True)
    (w/'evidence.json').write_text(json.dumps(out,indent=2)+'\n')
if __name__=='__main__':main()
