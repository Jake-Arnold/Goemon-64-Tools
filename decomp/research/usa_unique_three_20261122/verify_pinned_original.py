#!/usr/bin/env python3
"""Replay original USA native IDO/Splat ROM+ELF proof for two previously ASM-owned C functions (optional third research).

Reads private original ROM and prebuilt pinned upstream checkout. Creates a new scratch
copy and changes only its source, segment layout, and autogenerated outputs. Never
exports original ROM bytes, original ASM, compiled objects or ELF.

This is ORIGINAL-UPSTREAM G2, NOT canonical multi-accepted-C decomp.verify G2.
"""
from __future__ import annotations
import argparse
from collections import Counter
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess

PIN='7e2029c5c7beca705e7ded2c8fa85a5a21d1c3ee'
RETAIL='df8083a54296b8c151917c5333e1c85f014a2a66'
EXPANDED='6ea0ed71032ce08fc2745f412d84936382197494'
TARGETS={
 'func_8000A18C_AD8C':(0xAD8C,48,'a494dc6ba7f3ed16e1aa8232fd8e54d8948e40a7f8d2b22b80df3f6a3686a385'),
 'func_8000AAE8_B6E8':(0xB6E8,40,'790033f931cf2f15ea0e5d16204cd3caf6cec02a22e4ff55531aa196e9bcff77'),
 'func_8000AB30_B730':(0xB730,68,'3919d906ca430e5f56cc9c36a2e3320e5563166409bfb71756249445bd1f1531'),
}

def digest(path:Path,algorithm='sha1'):
 h=hashlib.new(algorithm)
 with path.open('rb') as f:
  for chunk in iter(lambda:f.read(1<<20),b''):h.update(chunk)
 return h.hexdigest()

def elf_records(path:Path):
 funcs,relocs=[],[]
 sym=subprocess.check_output(['readelf','-sW',str(path)],text=True)
 rel=subprocess.check_output(['readelf','-rW',str(path)],text=True)
 for line in sym.splitlines():
  m=re.match(r'^\s*\d+:\s+([0-9a-fA-F]+)\s+(\d+)\s+FUNC\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)',line)
  if m and int(m.group(2))>0:
   funcs.append((m.group(6),int(m.group(1),16),int(m.group(2)),m.group(3),m.group(4),m.group(5)))
 section=''
 for line in rel.splitlines():
  m=re.match(r"^Relocation section '([^']+)'",line)
  if m:section=m.group(1)
  m=re.match(r'^\s*([0-9a-fA-F]+)\s+[0-9a-fA-F]+\s+(R_MIPS_\S+)\s+[0-9a-fA-F]+\s+(\S+)',line)
  if m:relocs.append((section,int(m.group(1),16),m.group(2),m.group(3)))
 return funcs,relocs

def logged(command,cwd,env,log):
 with log.open('w') as out:
  proc=subprocess.run(command,cwd=cwd,env=env,stdout=out,stderr=subprocess.STDOUT)
 if proc.returncode:raise RuntimeError('Command failed (private log '+str(log)+'): '+repr(command))

def main():
 a=argparse.ArgumentParser(description=__doc__)
 for name in ['checkout','deps','runtime','out']:a.add_argument('--'+name,type=Path,required=True)
 a.add_argument('--jobs',type=int,default=16)
 a.add_argument('--try-third',action='store_true',help='Research-only 68-byte third function; deliberately fails strict ELF identity due to original trailing padding')
 args=a.parse_args()
 active={k:v for k,v in TARGETS.items() if args.try_third or k!='func_8000AB30_B730'}
 root=Path(__file__).resolve().parent
 checkout=args.checkout.resolve();deps=args.deps.resolve();runtime=args.runtime.resolve();out=args.out.resolve()
 if out.exists():raise SystemExit('Refusing to overwrite scratch output directory: '+str(out))
 actual_pin=subprocess.check_output(['git','rev-parse','HEAD'],cwd=checkout,text=True).strip()
 assert actual_pin==PIN,('Wrong original upstream commit',actual_pin)
 retail=checkout/'config/usa/baserom.z64';expanded=checkout/'config/usa/baserom.decompressed.z64'
 rebuilt=checkout/'build/usa/mnsg.z64';original_elf=checkout/'build/usa/mnsg.elf'
 assert retail.stat().st_size==16777216 and digest(retail)==RETAIL
 assert expanded.stat().st_size==33554432 and digest(expanded)==EXPANDED
 assert rebuilt.stat().st_size==33554432 and digest(rebuilt)==EXPANDED
 assert rebuilt.read_bytes()==expanded.read_bytes(),'Pinned baseline ROM build is not byte-identical'
 assert original_elf.is_file() and (checkout/'tools/ido-5.3/cc').is_file()
 code=expanded.read_bytes()
 for name,(rom_off,size,expected_sha) in active.items():
  actual=hashlib.sha256(code[rom_off:rom_off+size]).hexdigest()
  assert actual==expected_sha,('Original function hash mismatch',name,actual)
 out.mkdir(parents=True)
 work=out/'private_original_checkout_copy'
 shutil.copytree(checkout,work,symlinks=True)
 src=work/'src/92F0.c';old=src.read_text()
 marker='#pragma GLOBAL_ASM("asm/usa/nonmatchings/92F0/func_8000A18C_AD8C.s")'
 assert old.count(marker)==1
 c=(root/'source/func_8000A18C_AD8C.c').read_text();assert c.startswith('#include "common.h"\n')
 src.write_text(old.replace(marker,c.split('\n',1)[1].strip()))
 # The C source must cover all original B280 + BEA0 assembly, through C1D0.
 # This makes the final 0x2F0-byte original BBA8 function non-terminal and
 # preserves its 8 original NOPs as inter-function alignment, not FUNC extent.
 cfg=work/'config/usa/splat.yaml';t=cfg.read_text()
 assert t.count('    - [0xB280, asm]')==1
 assert t.count('    - [0xBEA0, asm]')==1
 assert t.count('    - [0xC1D0, asm]')==1
 t=t.replace('    - [0xB280, asm]','    - [0xB280, c, research_mixed_b280]',1)
 if args.try_third:
  t=re.sub(r'^    - \[0xBEA0, asm\].*\n','',t,count=1,flags=re.M)
 else:
  t=t.replace('    - [0xB280, c, research_mixed_b280]',
              '    - [0xB280, c, research_mixed_b280]\n    - [0xB730, asm]',1)
 cfg.write_text(t)
 names=[]
 segments=('B280','BEA0') if args.try_third else ('B280',)
 for segment in segments:
  raw=(checkout/'asm/usa'/f'{segment}.s').read_text()
  names+=re.findall(r'^nonmatching (func_\w+),',raw,re.M)
 if not args.try_third:
  names=[name for name in names if int(name.rsplit('_',1)[1],16)<0xB730]
 assert len(names)==(19 if args.try_third else 7) and len(set(names))==len(names)
 assert [x for x in active if x in names]==(
  ['func_8000AAE8_B6E8','func_8000AB30_B730'] if args.try_third else ['func_8000AAE8_B6E8'])
 text='#include "common.h"\n\n'
 for name in names:
  if name in active and name!='func_8000A18C_AD8C':
   c=(root/'source'/f'{name}.c').read_text();assert c.startswith('#include "common.h"\n')
   text+=c.split('\n',1)[1].strip()+'\n\n'
  else:
   text+=f'#pragma GLOBAL_ASM("asm/usa/nonmatchings/research_mixed_b280/{name}.s")\n'
 (work/'src/research_mixed_b280.c').write_text(text)
 env=os.environ.copy()
 env['PYTHONHOME']=str(runtime/'python')
 env['PYTHONPATH']=str(deps/'.venv/lib/python3.12/site-packages')
 env['PATH']=str(deps/'bin')+os.pathsep+env.get('PATH','')
 env['LD_LIBRARY_PATH']=str(runtime/'lib')+(os.pathsep+env['LD_LIBRARY_PATH'] if env.get('LD_LIBRARY_PATH') else '')
 py=str(runtime/'python/bin/python3.12')
 splat=str(deps/'.venv/bin/splat')
 logged([py,splat,'split','config/usa/splat.yaml'],work,env,out/'private_splat.log')
 for name in names:
  if name not in TARGETS:
   assert (work/'asm/usa/nonmatchings/research_mixed_b280'/f'{name}.s').is_file(),name
 logged(['make',f'-j{args.jobs}','VERSION=usa','build/usa/mnsg.z64'],work,env,out/'private_native_build.log')
 candidate=work/'build/usa/mnsg.z64';candidate_elf=work/'build/usa/mnsg.elf'
 assert digest(candidate)==EXPANDED
 assert candidate.read_bytes()==code,'Complete 32MiB original ROM byte identity failed'
 a_funcs,a_relocs=elf_records(original_elf)
 b_funcs,b_relocs=elf_records(candidate_elf)
 assert len(a_funcs)==len(b_funcs)==7376,(len(a_funcs),len(b_funcs))
 identities_match=Counter(a_funcs)==Counter(b_funcs)
 if args.try_third and not identities_match:
  # Observable original-upstream build blocker: unchanged final ASM function
  # absorbs 8 section-padding bytes in the mixed C object's FUNC symbol extent.
  missing=Counter(a_funcs)-Counter(b_funcs);extra=Counter(b_funcs)-Counter(a_funcs)
  print('FAILED_ELF THIRD C: first original-vs-candidate symbol differences',list(missing.items())[:4],list(extra.items())[:4])
 else:
  assert identities_match,'Original positive-size ELF function identity multiset mismatch'
 assert len(a_relocs)==len(b_relocs)==82216,(len(a_relocs),len(b_relocs))
 assert Counter(a_relocs)==Counter(b_relocs),'Original ELF relocation identity multiset mismatch'
 for name,(_,size,_) in active.items():
  sym=[f for f in b_funcs if f[0]==name]
  assert len(sym)==1 and sym[0][2]==size,('Native function extent failure',name,sym)
 report={'classification':'RESEARCH_ONLY_ORIGINAL_UPSTREAM_ROM_EXACT_NOT_CANONICAL_DECOMP_G2',
  'pin':PIN,'rom_sha1':EXPANDED,'retail_sha1':RETAIL,'rom_bytes_identical':33554432,
  'original_elf_sha256':digest(original_elf,'sha256'),
  'candidate_elf_sha256':digest(candidate_elf,'sha256'),
  'elf_positive_function_identities_exact':7376 if identities_match else 0,'elf_original_relocation_records_exact':82216,
  'targets':[{'name':n,'original_rom_offset':hex(off),'original_bytes':size,
    'original_function_sha256':sha,'source_sha256':digest(root/'source'/f'{n}.c','sha256')}
      for n,(off,size,sha) in active.items()],
  'canonical_decomp_verify':'NOT_RUN','canonical_semantic_relocations':'NOT_RUN',
  'strict_inventory':'NOT_RUN','decomp_local_ci':'NOT_RUN','accepted_delta':0}
 if args.try_third and not identities_match:
  report['classification']='RESEARCH_ONLY_THIRD_FAILED_ELF_DUE_TO_UNCHANGED_NEIGHBOR_PADDING'
 (out/'sanitized_report.json').write_text(json.dumps(report,indent=2)+'\n')
 print('PASS 33,554,432/33,554,432 original-USA ROM bytes (SHA1 '+EXPANDED+')')
 print('PASS 7,376/7,376 original ELF function identities' if identities_match else 'FAILED_ELF: 7,376 counts but one neighboring FUNC size differs')
 print('PASS 82,216/82,216 original ELF relocation tuples')
 print('PASS two original C functions / 88 original instruction bytes' if not args.try_third else 'PARTIAL: three original C functions / 156 bytes ROM exact but strict ELF mismatch')
 if not identities_match:raise SystemExit(2)
 print('RESEARCH_ONLY; canonical modern decomp.verify/inventory/full local_ci NOT_RUN')

if __name__=='__main__':main()
